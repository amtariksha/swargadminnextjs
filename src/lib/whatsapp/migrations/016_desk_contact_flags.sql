-- ─── desk_contact_flags ─────────────────────────────────────────────────────
-- phone: the 10-digit form (lib/desk/phone.ts toBackendPhone), written by
--        POST /api/desk/contact-flags only.
-- kind:  'internal' | 'customer' (lib/desk/constants.ts CONTACT_FLAG_KINDS);
--        validated by zod, no CHECK (a-schema.md section 1: CHECK on status only).
-- added_by / removed_by: String(app_db users.id), like desk_tickets.assigned_to.
CREATE TABLE IF NOT EXISTS public.desk_contact_flags (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone            TEXT        NOT NULL,
    kind             TEXT        NOT NULL,
    label            TEXT,
    added_by         TEXT        NOT NULL,
    added_by_name    TEXT,
    added_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    removed_at       TIMESTAMPTZ,
    removed_by       TEXT,
    removed_by_name  TEXT
);

-- ─── Row level security: ON, with NO policies ───────────────────────────────
-- service_role has BYPASSRLS and is the only role that reads or writes this
-- table. Do NOT copy the legacy "FOR ALL USING (true)" policy of the WACRM tables.
ALTER TABLE public.desk_contact_flags ENABLE ROW LEVEL SECURITY;

-- ─── Privileges ─────────────────────────────────────────────────────────────
-- Schema public carries ALTER DEFAULT PRIVILEGES that grant SELECT, INSERT,
-- UPDATE, DELETE on every new table to anon and authenticated, so these
-- REVOKEs are load-bearing, not decoration.
REVOKE ALL ON TABLE public.desk_contact_flags FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_contact_flags TO service_role;

REVOKE ALL ON SEQUENCE public.desk_contact_flags_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.desk_contact_flags_id_seq TO service_role;

-- ═══════════════════════════════════════════════════════════════════════════
-- PART 2 of 3 - index.  Paste this on its own.
--
-- Plain CREATE INDEX: the table was created empty in Part 1, so the build is
-- instant. The name and predicate are matched by 016_verify.sql.
-- ═══════════════════════════════════════════════════════════════════════════

-- At most one active flag per phone. A second POST for the same phone gets
-- 23505, which the route answers with the existing row.
CREATE UNIQUE INDEX IF NOT EXISTS uq_desk_contact_flags_phone_active
    ON public.desk_contact_flags (phone)
    WHERE removed_at IS NULL;

-- ═══════════════════════════════════════════════════════════════════════════
-- PART 3 of 3 - seed: the desk_staff_phones setting.  Paste this on its own.
--
-- A JSON array of 10-digit phones, written only by the Desk tick when the
-- backend's list changes. WHERE NOT EXISTS because global rows have
-- org_id NULL, which no ON CONFLICT target matches.
-- ═══════════════════════════════════════════════════════════════════════════

INSERT INTO public.app_settings (key, value, org_id, updated_at)
SELECT 'desk_staff_phones', '[]', NULL, now()
WHERE NOT EXISTS (
    SELECT 1
    FROM public.app_settings s
    WHERE s.key = 'desk_staff_phones'
      AND s.org_id IS NULL
);
