-- ─── Row level security: ON, with NO policies ───────────────────────────────
-- service_role has BYPASSRLS and is the only role that reads or writes these
-- tables. With no policy, anon and authenticated see nothing even if a grant
-- is added by mistake later. Do NOT copy the legacy "FOR ALL USING (true)"
-- policy from the WACRM tables.
ALTER TABLE public.desk_categories     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.desk_tickets        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.desk_ticket_events  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.desk_ticket_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.desk_action_items   ENABLE ROW LEVEL SECURITY;

-- ─── Privileges: tables ─────────────────────────────────────────────────────
-- Schema public carries ALTER DEFAULT PRIVILEGES that grant SELECT, INSERT,
-- UPDATE, DELETE on every new table to anon and authenticated
-- (swarg-admin-nextjs/scripts/drop-old-payload-public-schema.sql:46-47), so
-- these REVOKEs are load-bearing, not decoration.
REVOKE ALL ON TABLE public.desk_categories     FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.desk_tickets        FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.desk_ticket_events  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.desk_ticket_actions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.desk_action_items   FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_categories     TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_tickets        TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_ticket_events  TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_ticket_actions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.desk_action_items   TO service_role;

-- ─── Privileges: identity sequences ─────────────────────────────────────────
-- The default privileges above cover TABLES only, so nothing is granted on
