REVOKE ALL ON SEQUENCE public.desk_ticket_events_id_seq   FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.desk_ticket_actions_id_seq  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.desk_action_items_id_seq    FROM PUBLIC, anon, authenticated;

GRANT USAGE, SELECT ON SEQUENCE public.desk_tickets_ticket_no_seq  TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.desk_ticket_events_id_seq   TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.desk_ticket_actions_id_seq  TO service_role;
