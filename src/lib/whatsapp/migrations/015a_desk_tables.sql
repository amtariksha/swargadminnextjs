-- Swarg Desk - Migration 015a · desk tables, indexes, seeds
--
-- Desk records one ticket for every episode of a WhatsApp conversation
-- (docs/desk-ticketing/00-blueprint.md). This file creates the five desk
-- tables in schema public, their indexes, and the category and settings
-- seeds. 015b adds three nullable columns to public.messages.
--
-- STRICTLY ADDITIVE
--   - 5 new tables: desk_categories, desk_tickets, desk_ticket_events,
--     desk_ticket_actions, desk_action_items.
--   - 33 desk_categories rows and 16 public.app_settings rows (org_id NULL).
--     Every engine and UI flag is seeded OFF.
--   - No existing table is altered. The only contact with existing tables is
--     two foreign keys from desk_tickets to conversations and contacts.
--   - No function, view, trigger or RLS policy is created.
--
-- SECURITY MODEL
--   RLS enabled with no policies; every privilege revoked from PUBLIC, anon
--   and authenticated; explicit grants to service_role only. The backend role
--   app_db_app gets nothing: the backend never reads or writes desk tables.
--
-- HOW TO APPLY (operator)
--   No migration runner exists. Paste into the Supabase SQL editor of project
--   reyrthufoezeqymzwaer (older files call it "the WACRM project"; since
--   2026-10-05 it is the project that also holds app_db).
--
--   The editor wraps whatever you paste in ONE transaction. So this file has
--   no BEGIN/COMMIT and no CREATE INDEX CONCURRENTLY, and it is pasted in
--   THREE parts, one at a time, in order. Each part is then all-or-nothing.
--
--   Run Part 1 outside 05:00-09:00 IST: it locks conversations and contacts
--   for an instant to attach two foreign keys. If it stops with
--   "canceling statement due to lock timeout" (55P03) nothing was changed;
--   paste it again.
--
--   Idempotent: every part can be pasted again at any time.
--   Afterwards run 015_verify.sql; every row must read OK.
