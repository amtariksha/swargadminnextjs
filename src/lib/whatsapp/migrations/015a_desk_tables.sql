-- D3: at most one unresolved ticket per conversation. The predicate must stay
-- exactly "status <> 'resolved'"; repo.ts filters with .neq('status','resolved')
-- so the planner can use this and the two queue indexes below.
CREATE UNIQUE INDEX IF NOT EXISTS uq_desk_tickets_open_conversation
    ON public.desk_tickets (conversation_id)
    WHERE status <> 'resolved';

-- Latest ticket (resolved or not) of a conversation: reopen-window lookup,
-- previous_ticket_id, and the ON DELETE SET NULL from conversations.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_conversation_opened
    ON public.desk_tickets (conversation_id, opened_at DESC);

-- The queue: unresolved tickets only, by queue and waiting time.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_open_queue
    ON public.desk_tickets (queue, awaiting_reply_since)
    WHERE status <> 'resolved';

-- "Mine" and "Unassigned" tabs.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_open_assignee
    ON public.desk_tickets (assigned_to)
    WHERE status <> 'resolved';

-- Stats and review paging: fetchAllPaged orders by (opened_at, id).
CREATE INDEX IF NOT EXISTS idx_desk_tickets_opened
    ON public.desk_tickets (opened_at, id);

-- Resolved-in-window reads and the "Needs wrap-up" tab.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_resolved
    ON public.desk_tickets (resolved_at DESC)
    WHERE resolved_at IS NOT NULL;

-- Customer history: previous tickets, "other open tickets for this customer",
-- repeat complainers, and the first-order signal that resolves a sales ticket.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_phone_opened
    ON public.desk_tickets (customer_phone, opened_at DESC);

CREATE INDEX IF NOT EXISTS idx_desk_tickets_user_opened
    ON public.desk_tickets (backend_user_id, opened_at DESC)
    WHERE backend_user_id IS NOT NULL;

-- Serves the ON DELETE SET NULL from contacts.
CREATE INDEX IF NOT EXISTS idx_desk_tickets_contact
    ON public.desk_tickets (contact_id)
    WHERE contact_id IS NOT NULL;

-- Ticket timeline, and the review page's health lists (by event type and day).
CREATE INDEX IF NOT EXISTS idx_desk_ticket_events_ticket_created
    ON public.desk_ticket_events (ticket_id, created_at);

CREATE INDEX IF NOT EXISTS idx_desk_ticket_events_type_created
    ON public.desk_ticket_events (type, created_at);

-- Actions of a ticket, and the refunds-and-credits list for a period.
CREATE INDEX IF NOT EXISTS idx_desk_ticket_actions_ticket_created
    ON public.desk_ticket_actions (ticket_id, created_at);

CREATE INDEX IF NOT EXISTS idx_desk_ticket_actions_type_created
    ON public.desk_ticket_actions (action_type, created_at);

-- One refund / wallet-credit reference belongs to one ticket. The two
-- action_type literals must match lib/desk/constants.ts exactly.
CREATE UNIQUE INDEX IF NOT EXISTS uq_desk_ticket_actions_money_ref
    ON public.desk_ticket_actions (ref_type, ref_id)
    WHERE action_type IN ('refund', 'wallet_credit') AND ref_id IS NOT NULL;

-- Morning-meeting carry-over (open items by due date) and items of a ticket.
CREATE INDEX IF NOT EXISTS idx_desk_action_items_status_due
    ON public.desk_action_items (status, due_date);

CREATE INDEX IF NOT EXISTS idx_desk_action_items_ticket
    ON public.desk_action_items (ticket_id)
    WHERE ticket_id IS NOT NULL;

